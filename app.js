// Cheapest gem spend that reaches the pick-up points.
// 11-pull (3000💎 → 33 pts) and single (300💎 → 3 pts) combine, e.g. 400 pts = 12 multi + 2 single = 36,600💎.
// Daily Discount is left out (once per day, paid gems only).
function pityInfo(s) {
  if (!s.points) return null;
  const opts = s.options
    .filter(o => /Gems/.test(o.cost) && !/Discount/i.test(o.label))
    .map(o => ({
      label: o.label, tier: o.tier, pts: o.points || 0,
      gems: parseInt(o.cost.replace(/[^\d]/g, ''), 10),
      max: /No Limit/i.test(o.limit) ? Infinity : (parseInt((o.limit.match(/\d+/) || [])[0], 10) || Infinity),
    }));
  if (!opts.some(o => o.pts)) return { points: s.points };

  // Tiered scouts unlock in order, so points come from pulling tier 1, 2, 3… in sequence
  if (opts.some(o => o.tier)) {
    let pts = 0, gems = 0, n = 0;
    for (const o of opts) { if (pts >= s.points) break; pts += o.pts; gems += o.gems; n++; }
    return pts >= s.points ? { points: s.points, gems, plan: [`Tier 1 → ${n}`] } : { points: s.points };
  }

  // Merge identical pulls (the file lists each limited 11-pull step separately)
  const groups = [];
  for (const o of opts.filter(o => o.pts)) {
    const g = groups.find(x => x.label === o.label && x.gems === o.gems && x.pts === o.pts);
    if (g) g.max += o.max; else groups.push({ ...o });
  }
  groups.sort((a, b) => b.pts - a.pts);
  // Exhaustive search over counts — at most a few groups and ~150 pulls, so this stays tiny
  let best = null;
  const walk = (i, pts, gems, counts) => {
    if (best && gems >= best.gems) return;
    if (pts >= s.points) { best = { gems, counts: [...counts] }; return; }
    if (i === groups.length) return;
    const g = groups[i];
    const need = Math.min(g.max, Math.ceil((s.points - pts) / g.pts));
    for (let n = need; n >= 0; n--) { counts[i] = n; walk(i + 1, pts + n * g.pts, gems + n * g.gems, counts); }
    counts[i] = 0;
  };
  walk(0, 0, 0, groups.map(() => 0));
  if (!best) return { points: s.points };
  return {
    points: s.points, gems: best.gems,
    plan: groups.map((g, i) => {
      if (!best.counts[i]) return '';
      const kind = /[x×]\s*11\b/.test(g.label) ? 'multi' : /[x×]\s*1$/.test(g.label) ? 'single' : g.label.replace(/Sync Pair /, '');
      return `${best.counts[i]} ${kind}`;
    }).filter(Boolean),
  };
}

