// Run a DOM swap inside a View Transition when the browser has them; `kind` picks the CSS animation
function withTransition(swap, kind = 'page') {
  if (!document.startViewTransition || calm() || document.hidden) return swap();
  const root = document.documentElement;
  root.dataset.vt = kind;
  // A pair card was clicked: its sprites fly to the pair page's hero (see "Shared sprites" below)
  if (kind === 'page' && (morphEls.some(el => el.isConnected) || $('#dh-poke'))) root.dataset.morph = '';
  const vt = document.startViewTransition(swap);
  const done = () => { delete root.dataset.vt; delete root.dataset.morph; };
  // A transition the browser gives up on (tab hidden mid-way, a newer one starting) still swaps the page; nothing to report
  vt.finished.then(done, done);
  vt.ready.catch(() => {});
}

