function route() {
  const [, name = '', arg = ''] = location.hash.replace(/^#/, '').split('/');
  const fn = routes[name] || renderHome;
  // Opening a pair: give its details a moment to arrive, so the page swaps once (and the sprites can fly over)
  // instead of flashing "Loading…" in between
  if (name === 'pair' && routed && !route.inPlace && !route.waited && !pairDetail[decodeURIComponent(arg)] && D.pairs.some(x => x.id === decodeURIComponent(arg))) {
    route.waited = true;
    const go = () => { if (route.waited) route(); };
    Promise.race([loadPairDetail(decodeURIComponent(arg)), new Promise(r => setTimeout(r, 450))]).then(go, go);
    return;
  }
  route.waited = false;
  if (!route.inPlace) { scrollMemo[routeHash] = scrollY; routeHash = location.hash; }
  const back = traversing && !route.inPlace ? scrollMemo[location.hash] : null;
  traversing = false;
  markNav(name, arg);
  tipEl.classList.remove('show');
  const swap = () => {
    view.innerHTML = fn(decodeURIComponent(arg)) || '';
    afterRender[name]?.(decodeURIComponent(arg));
    if (back != null) window.scrollTo(0, back);
    else if (!location.hash.includes('#scouts/')) window.scrollTo(0, 0);
    stagger();
    reveal();
    countUp();
  };
  // First paint and the async detail reload swap in place; real navigations cross-fade
  routed && !route.inPlace ? withTransition(swap) : swap();
  routed = true;
  route.inPlace = false;
}
