function hpChart(g) {
  const rows = g.stages.map((s, i) => {
    const u = s.leaders[0]?.units || [];
    const c = g.circuits.find(c => c.name === s.name);
    return { i, s, c, hp: u[0]?.hp || 0, side: u[1]?.hp || 0, atk: u[0]?.atk || 0 };
  });
  const max = Math.max(...rows.map(r => r.hp), 1);
  return ui`
    <div class="hp-bars">${rows.map(r => `
      <div class="hp-col ${r.i === gymStage ? 'sel' : ''}" data-stage="${r.i}"
        ${tip(r.s.name, `HP Center: ${fmtN(r.hp)}\nHP Left/Right: ${fmtN(r.side)}\nAttack: ${fmtN(r.atk)}${r.c ? `\n${fmtN(r.c.pts)} pts · ${r.c.ball}` : ''}`)}>
        <span class="hp-val">${fmtShort(r.hp)}</span>
        <span class="hp-bar" style="height:${Math.max(r.hp / max * 100, 1.5)}%;--c:${BALLS[r.c?.ball]?.c || 'var(--accent)'}"></span>
      </div>`).join('')}
    </div>
    <div class="hp-lbl">${rows.map(r => `<span>${stageShort(r.s.name)}</span>`).join('')}</div>
    <div class="matrix-legend">${Object.entries(BALLS).map(([k, b]) => `<span><i class="gl-swatch" style="background:${b.c}"></i>${k} tier</span>`).join('')}<span class="muted">HP của boss Center (mọi Gym Leader bằng nhau trong cùng circuit)</span></div>`;
}

function stageDetail(g) {
  const s = g.stages[gymStage];
  const c = g.circuits.find(c => c.name === s.name);
  return ui`
    <h2 class="section-title">Chi tiết: ${esc(s.name)} ${c ? `<span class="count">${img(`assets/items/${BALLS[c.ball]?.img}.png`, 'ball-ico')} ${fmtN(c.pts)} pts · ${esc(c.kind)}</span>` : ''}</h2>
    <div class="filter-line">${g.stages.map((x, i) => `<button class="chip ${i === gymStage ? 'on' : ''}" data-stage="${i}">${stageShort(x.name)}</button>`).join('')}</div>
    ${s.name.includes('onward') && g.rotateNote ? `<p class="rule-line" style="margin-top:12px">🔄 ${esc(g.rotateNote)}</p>` : ''}
    <div class="stage-detail">${s.leaders.map(l => `
      <div class="unit" style="--tc:${TYPE_COLORS[l.type]}">
        <h4>${img(g.leaderSprites[l.name], 'sprite')}${esc(l.name)} ${typeBadge(l.type, true)}</h4>
        ${l.theme ? `<div class="rule-line"><b>${esc(l.theme)}</b>${l.rule ? `<br><span class="muted">${esc(l.rule)}</span>` : ''}</div>` : ''}
        ${l.rules.map((r, k) => `<div class="rule-line"><b>Rules ${k + 1}:</b> ${esc(r)}</div>`).join('')}
        ${l.units.map(u => ui`
          <div style="margin-top:8px"><b>${u.pos === 'Center' ? '👑 Center' : '👥 Left / Right'}</b> <span class="muted">· yếu</span> ${typeBadge(u.weakness, true)}</div>
          <div class="ustats">
            <div><span>HP</span>${fmtN(u.hp)}</div><div><span>Atk / SpA</span>${fmtN(u.atk)}</div><div><span>Speed</span>${fmtN(u.spe)}</div>
          </div>
          ${u.focus.length ? `<div>${u.focus.map(f => `<span class="tag sm">🔸 ${esc(f)}</span>`).join(' ')}</div>` : ''}
          ${u.passives.length || u.reductionMods.length ? `<ul>
            ${u.passives.map(x => `<li>🔹 ${esc(x)}</li>`).join('')}
            ${u.reduction ? `<li class="muted">♦️ DMG Reduction: ${esc(u.reduction)}</li>` : ''}
            ${u.reductionMods.map(x => `<li class="muted">● ${esc(x)}</li>`).join('')}
          </ul>` : ''}`).join('')}
      </div>`).join('')}
    </div>`;
}

document.addEventListener('click', e => {
  const st = e.target.closest('[data-stage]');
  if (!st || !location.hash.startsWith('#/gym')) return;
  gymStage = +st.dataset.stage;
  const gi = location.hash.split('/')[2];
  const g = D.gyms[gi !== undefined && gi !== '' ? +gi : D.gyms.length - 1];
  $('#stage-detail').innerHTML = stageDetail(g);
  stagger($('#stage-detail'));
  $('#hpchart').innerHTML = hpChart(g);
  $$('.matrix th.stage').forEach(th => th.classList.toggle('sel', +th.dataset.stage === gymStage));
  if (!st.closest('#stage-detail')) $('#stage-detail').scrollIntoView({ behavior: 'smooth', block: 'start' });
});

