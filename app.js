// Swap a sprite for another one. The new image is loaded off screen first and everything (source, .anim, its --w / --h,
// whatever `then` changes) is applied in one go: switching the class before the image arrived left the old sprite
// without a size or position for a moment, so it shrank into the corner before the new one showed.
const setAnimSrc = (el, src, then) => {
  const token = el._swap = (el._swap || 0) + 1;
  const apply = (url, pre) => {
    if (el._swap !== token || !el.isConnected) return;
    const anim = !!pre && url === ANIM[src];
    el.classList.toggle('anim', anim);
    if (anim) { el.style.setProperty('--w', pre.naturalWidth); el.style.setProperty('--h', pre.naturalHeight); }
    else { el.style.removeProperty('--w'); el.style.removeProperty('--h'); }
    el.dataset.static = src;
    el.onerror = anim ? () => animFailed(el) : () => { el.onerror = null; el.src = PLACEHOLDER; };
    el.src = url;
    then?.();
  };
  const load = (url, fail) => { const pre = new Image(); pre.onload = () => apply(url, pre); pre.onerror = fail; pre.src = url; };
  if (ANIM[src]) load(ANIM[src], () => load(src, () => apply(PLACEHOLDER)));
  else load(src, () => apply(PLACEHOLDER));
};

