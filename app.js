// Where a full grid's energy goes: by tile kind, and by the move a tile boosts
function gridEnergy(cells, colors, energy) {
  const kinds = colors.map(k => { const l = cells.filter(x => x.color === k); return { k, n: l.length, e: l.reduce((a, x) => a + x.energy, 0) }; });
  const moves = new Map();
  for (const c of cells) if (c.move) { const m = moves.get(c.move) || moves.set(c.move, { n: 0, e: 0 }).get(c.move); m.n++; m.e += c.energy; }
  const mv = [...moves.entries()].sort((a, b) => b[1].e - a[1].e), mmax = mv[0]?.[1].e || 1;
  const row = (sw, label, n, e, w, color) => `<div class="ge-row ${sw ? '' : 'nosw'}">${sw}<span class="ge-l">${esc(label)}</span>
    <span class="ge-track"><span style="width:${w}%;background:${color}"></span></span><span class="ge-v">⚡${fmtN(e)}</span><small>${n}</small></div>`;
  return `<div class="ge">
    <div class="ge-h">${L('Energy by tile kind', 'Energy theo loại ô')}<small>${L('tiles', 'ô')}</small></div>
    ${kinds.map(x => row(gridSwatch(x.k), GRID_COLORS[x.k].label, x.n, x.e, energy ? x.e / energy * 100 : 0, GRID_COLORS[x.k].hex === 'rainbow' ? 'var(--accent)' : GRID_COLORS[x.k].hex)).join('')}
    ${mv.length ? `<div class="ge-h">${L('Energy by move', 'Energy theo move')}<small>${L('tiles', 'ô')}</small></div>
    ${mv.map(([m, x]) => row('', m, x.n, x.e, x.e / mmax * 100, 'var(--accent-2)')).join('')}` : ''}
  </div>`;
}

