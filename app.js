function reveal(root = view) {
  if (!revealer || calm() || !root) return;
  for (const el of root.children) {
    if (el.classList.contains('rv') || el.tagName === 'DIALOG' || !el.offsetHeight) continue;
    if (el.getBoundingClientRect().top < innerHeight * .92) continue;
    el.classList.add('rv');
    revealer.observe(el);
  }
}

// Numbers count up once (stat tiles): <span data-count="678">
function countUp(root = view) {
  for (const el of $$('[data-count]', root)) {
    const to = +el.dataset.count;
    el.removeAttribute('data-count');
    if (calm() || !(to > 0)) continue;
    const t0 = performance.now(), dur = 900;
    const step = t => {
      const k = Math.min(1, (t - t0) / dur);
      el.textContent = Math.round(to * (1 - (1 - k) ** 3));
      if (k < 1 && el.isConnected) requestAnimationFrame(step);
    };
    el.textContent = '0';
    requestAnimationFrame(step);
  }
}

// The trainer's line is typed out like an in-game text box; the untyped rest keeps its space, so nothing moves
function typeOut(el) {
  if (!el || calm() || el.dataset.typed) return;
  el.dataset.typed = '1';
  const text = el.textContent, a = document.createElement('span'), b = document.createElement('span');
  b.style.visibility = 'hidden';
  b.textContent = text;
  el.replaceChildren(a, b);
  el.setAttribute('aria-label', text);
  const per = Math.max(1, Math.ceil(text.length / 70)), t0 = performance.now() + 350;
  let shown = 0;
  const step = t => {
    if (!el.isConnected) return;
    const n = Math.min(text.length, Math.max(0, Math.floor((t - t0) / 22) * per));
    if (n !== shown) { shown = n; a.textContent = text.slice(0, n); b.textContent = text.slice(n); }
    if (n < text.length) requestAnimationFrame(step); else el.classList.add('typed');
  };
  requestAnimationFrame(step);
}

// Wide strips (release timeline): drag to scroll with the mouse, and fade the edge that has more to show
function scrollStrip(el) {
  if (!el || el._strip) return;
  el._strip = true;
  const mark = () => {
    el.classList.toggle('more-l', el.scrollLeft > 4);
    el.classList.toggle('more-r', el.scrollLeft + el.clientWidth < el.scrollWidth - 4);
  };
  el.addEventListener('scroll', mark, { passive: true });
  mark();
  el.addEventListener('pointerdown', e => { el._dragged = false; if (e.pointerType === 'mouse' && !e.button) stripDrag = { el, x: e.clientX, left: el.scrollLeft, moved: false }; });
  // A drag that ends on a pair must not open it
  el.addEventListener('click', e => { if (el._dragged) { e.preventDefault(); e.stopPropagation(); el._dragged = false; } }, true);
  el.addEventListener('dragstart', e => e.preventDefault());
}
