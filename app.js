// The grid is drawn as flat-topped hexagons with straight, crisp edges (vector paths at the screen's pixel density),
// each with a raised bevel and its pixel-art glyph. `exporting` draws on a canvas of its own (for the picture) at a fixed size,
// with no hover. Datamine cube coords (q, r): q to the right, r up — the in-game placement.
const hexCorners = (cx, cy, R) => Array.from({ length: 6 }, (_, i) => [cx + R * Math.cos(Math.PI / 3 * i), cy + R * Math.sin(Math.PI / 3 * i)]);
function hexPath(ctx, cx, cy, R) {
  ctx.beginPath();
  hexCorners(cx, cy, R).forEach(([x, y], i) => (i ? ctx.lineTo(x, y) : ctx.moveTo(x, y)));
  ctx.closePath();
}
function drawGrid(p, cv = $('#hexcanvas'), exporting = false) {
  if (!cv || !p) return;
  // Builder: lit tiles in full colour, unlinked picks dashed, level-locked ones dark with a padlock, the rest faded
  const B = exporting ? (build.pairId === p.id ? build : null) : buildFor(p);
  const linked = B ? linkedTiles(gridIndex(p), B.active) : null;
  const css = getComputedStyle(document.documentElement);
  const tok = n => css.getPropertyValue(n).trim() || '#000';
  const [bg, dot, line, shadow, accent, ink, danger] = ['--panel-2', '--bg-dot', '--line-strong', '--shadow', '--accent', '--ink', '--danger'].map(tok);
  const LOCKED = ['#60647a', '#3e4150', '#2a2d38'];

  const cells = p.grid;
  const unit = c => ({ x: 1.5 * c.q, y: -Math.sqrt(3) * (c.r + c.q / 2) });
  const pts = cells.map(unit).concat([{ x: 0, y: 0 }]);
  const minX = Math.min(...pts.map(v => v.x)), maxX = Math.max(...pts.map(v => v.x));
  const minY = Math.min(...pts.map(v => v.y)), maxY = Math.max(...pts.map(v => v.y));
  const spanX = maxX - minX + 2, spanY = maxY - minY + Math.sqrt(3);
  const pad = 14;
  let R;
  if (exporting) R = Math.min(34, 580 / spanY, 640 / spanX);
  else {
    const box = Math.max(200, cv.parentElement.clientWidth - 24);
    R = Math.max(12, Math.min((box - pad * 2) / spanX, (Math.min(640, innerHeight * .8) - pad * 2) / spanY, 34));
  }
  const W = Math.ceil(spanX * R + pad * 2), H = Math.ceil(spanY * R + pad * 2);
  const dpr = exporting ? 1 : Math.min(3, window.devicePixelRatio || 1);
  cv.width = Math.round(W * dpr); cv.height = Math.round(H * dpr);
  if (!exporting) { cv.style.width = W + 'px'; cv.style.height = H + 'px'; }
  const ctx = cv.getContext('2d');
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  const pos = c => { const v = unit(c); return { x: (v.x - minX + 1) * R + pad, y: (v.y - minY + Math.sqrt(3) / 2) * R + pad }; };

  // Background with a dot lattice
  ctx.fillStyle = bg; ctx.fillRect(0, 0, W, H);
  ctx.fillStyle = dot;
  for (let y = 4; y < H; y += 8) for (let x = 4; x < W; x += 8) ctx.fillRect(x, y, 1.5, 1.5);

  const state = h => {
    if (h.center || !B) return { a: h.center || detail.gridColors.has(h.color) ? 1 : .22 };
    if (B.active.has(h.n)) return linked.has(h.n) ? { a: 1, on: true } : { a: .9, on: true, loose: true };
    if (tileLevel(h) > B.lv) return { a: 1, locked: true };
    return { a: .3 };
  };
  const hexes = [{ center: true, q: 0, r: 0 }, ...cells];
  const r0 = R * .94;   // a hairline gap between tiles keeps every edge readable

  // Shadows first so they never cover a neighbour
  for (const h of hexes) {
    const { x, y } = pos(h);
    ctx.globalAlpha = state(h).a;
    ctx.fillStyle = shadow; hexPath(ctx, x + 2.5, y + 2.5, r0); ctx.fill();
  }
  for (const h of hexes) {
    const { x, y } = pos(h), st = state(h);
    const sel = !h.center && !exporting && detail.cell === h.n;
    const hov = !h.center && !exporting && gridHover === h.n;
    const pal = h.center ? [accent, accent, accent] : st.locked ? LOCKED : (GRID_PAL[h.color] || GRID_PAL.blue);
    ctx.globalAlpha = st.a;
    // Raised bevel: dark rim, light top-left edge, flat face
    ctx.fillStyle = h.center ? accent : pal[2]; hexPath(ctx, x, y, r0); ctx.fill();
    if (!h.center) {
      ctx.save(); hexPath(ctx, x, y, r0); ctx.clip();
      ctx.fillStyle = pal[0]; hexPath(ctx, x - R * .07, y - R * .08, r0 * .86); ctx.fill();
      ctx.restore();
    }
    if (h.color === 'rainbow' && !st.locked) {
      const g = ctx.createLinearGradient(x - r0, y - r0, x + r0, y + r0);
      RAINBOW.forEach((c, i) => g.addColorStop(i / (RAINBOW.length - 1), c));
      ctx.fillStyle = g;
    } else ctx.fillStyle = h.center ? accent : pal[1];
    hexPath(ctx, x, y, r0 * .78); ctx.fill();
    // Outline: crisp and straight; accent when pinned, white when lit, dashed red when picked but not linked yet
    ctx.lineJoin = 'round';
    ctx.lineWidth = sel || st.on ? 2.6 : 1.8;
    ctx.strokeStyle = sel ? accent : st.loose ? danger : st.on ? '#ffffff' : hov ? ink : line;
    if (st.loose) ctx.setLineDash([R * .22, R * .16]);
    hexPath(ctx, x, y, r0); ctx.stroke();
    ctx.setLineDash([]);
    if (st.on && !st.loose) { ctx.lineWidth = 1.4; ctx.strokeStyle = line; hexPath(ctx, x, y, r0 + 1.6); ctx.stroke(); }
    // A grid-expansion tile that hasn't opened yet: a dotted accent ring just outside the tile
    if (!h.center && !sel && !st.loose && expandPending(h)) {
      ctx.lineWidth = 1.6; ctx.strokeStyle = accent; ctx.setLineDash([R * .1, R * .12]);
      hexPath(ctx, x, y, r0 + 2.4); ctx.stroke(); ctx.setLineDash([]);
    }
    // The 5×5 pixel glyph, outlined for contrast
    const glyph = GLYPHS[h.center ? 'center' : st.locked ? 'lock' : h.color];
    if (glyph) {
      const px = Math.max(2, Math.round(R / 8 * 2) / 2), gx = x - px * 2.5, gy = y - px * 2.5;
      const onG = (i, j) => glyph[j]?.[i] === '#';
      ctx.fillStyle = line;
      for (let j = -1; j <= 5; j++) for (let i = -1; i <= 5; i++)
        if (!onG(i, j) && [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([di, dj]) => onG(i + di, j + dj))) ctx.fillRect(gx + i * px, gy + j * px, px, px);
      ctx.fillStyle = '#ffffff';
      for (let j = 0; j < 5; j++) for (let i = 0; i < 5; i++) if (onG(i, j)) ctx.fillRect(gx + i * px, gy + j * px, px, px);
    }
  }
  ctx.globalAlpha = 1;
  Object.assign(cv, { _cells: cells, _hit: cells.map(c => ({ c, ...pos(c) })), _R: r0 });
  return { W, H };
}

// The tile under the pointer: inside its hexagon (the inscribed circle is close enough and never overlaps a neighbour)
function gridCellAt(cv, e) {
  const r = cv.getBoundingClientRect(), x = e.clientX - r.left, y = e.clientY - r.top, lim = (cv._R || 0) * .96;
  let best = null, bd = Infinity;
  for (const h of cv._hit || []) { const d = Math.hypot(h.x - x, h.y - y); if (d < bd) { bd = d; best = h.c; } }
  return bd <= lim ? best : null;
}
